CREATE TABLE auth0_transactions (
    id TEXT PRIMARY KEY,
    browser_id TEXT NOT NULL,
    data JSONB NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE auth_sessions (
    session_id TEXT PRIMARY KEY,
    session_data JSONB NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE bgg_redirects (
    key BYTEA PRIMARY KEY,
    value BYTEA NOT NULL,
    expires INT NOT NULL
);

CREATE TABLE bgg_responses (
    key BYTEA PRIMARY KEY,
    value BYTEA NOT NULL,
    expires INT NOT NULL
);

CREATE TABLE users (
    id SERIAL PRIMARY KEY,
    username VARCHAR(30) UNIQUE,
    email TEXT,
    password_hash VARCHAR(255),
    bio TEXT DEFAULT '',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    profile_pic TEXT,
    auth0_sub TEXT UNIQUE,
    display_name VARCHAR(80),
    auth0_avatar_url TEXT,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    setup_complete BOOLEAN NOT NULL DEFAULT FALSE,
    hosted_events_visibility TEXT NOT NULL DEFAULT 'public'
        CHECK (hosted_events_visibility IN ('public', 'friends', 'private')),
    attending_events_visibility TEXT NOT NULL DEFAULT 'public'
        CHECK (attending_events_visibility IN ('public', 'friends', 'private')),
    friends_visibility TEXT NOT NULL DEFAULT 'public'
        CHECK (friends_visibility IN ('public', 'friends', 'private')),
    followers_visibility TEXT NOT NULL DEFAULT 'public'
        CHECK (followers_visibility IN ('public', 'friends', 'private'))
);

CREATE TABLE blocked (
    blocking INT REFERENCES users(id) ON DELETE CASCADE,
    blocked INT REFERENCES users(id) ON DELETE CASCADE,
    date_blocked TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (blocking, blocked)
);

CREATE TABLE event_calendars (
    id SERIAL,
    user_available INT REFERENCES users(id) ON DELETE CASCADE,
    time_available TSRANGE NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id, user_available)
);

CREATE TABLE events (
    id SERIAL PRIMARY KEY,
    public_id TEXT NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    gameid INT NOT NULL,
    game_name TEXT,
    game_categories TEXT[],
    hostid INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    calendarid INT,
    address VARCHAR(255) NOT NULL,
    time TIMESTAMPTZ,
    expected_duration DOUBLE PRECISION NOT NULL,
    max_attendees INT NOT NULL,
    description VARCHAR(4095) NOT NULL,
    status VARCHAR(255) NOT NULL,
    visibility TEXT NOT NULL DEFAULT 'public'
        CHECK (visibility IN ('public', 'friends', 'private')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    min_attendees INT NOT NULL DEFAULT 1
);

CREATE TABLE friend_invitations (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token TEXT NOT NULL UNIQUE,
    max_uses INT NOT NULL CHECK (max_uses > 0),
    use_count INT NOT NULL DEFAULT 0 CHECK (use_count BETWEEN 0 AND max_uses),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL CHECK (expires_at > created_at),
    revoked BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE friend_requests (
    requester_id INT REFERENCES users(id) ON DELETE CASCADE,
    recipient_id INT REFERENCES users(id) ON DELETE CASCADE,
    accepted BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (requester_id, recipient_id),
    CHECK (requester_id <> recipient_id)
);

CREATE TABLE friends (
    follower INT REFERENCES users(id) ON DELETE CASCADE,
    followed INT REFERENCES users(id) ON DELETE CASCADE,
    date_followed TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (follower, followed)
);

CREATE TABLE event_participation (
    id SERIAL REFERENCES events(id),
    user_interested INT REFERENCES users(id) ON DELETE CASCADE,
    is_host BOOLEAN NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id, user_interested)
);

CREATE TABLE notifications (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind TEXT NOT NULL,
    message TEXT NOT NULL,
    user_id INT REFERENCES users(id) ON DELETE SET NULL,
    event_id INT REFERENCES events(id) ON DELETE SET NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX expires_idx ON bgg_responses (expires);

CREATE INDEX friend_invitations_owner_created
    ON friend_invitations (owner_id, created_at DESC);

CREATE UNIQUE INDEX friend_requests_pair
    ON friend_requests (LEAST(requester_id, recipient_id), GREATEST(requester_id, recipient_id));

CREATE INDEX notifications_recipient_created
    ON notifications (recipient_id, created_at DESC, id DESC);

CREATE INDEX notifications_unread_recipient
    ON notifications (recipient_id) WHERE NOT is_read;